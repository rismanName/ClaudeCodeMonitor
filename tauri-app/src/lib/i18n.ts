/** Reactive translator: `$t('key', { v: '1.0' })`. Falls back to English, then the key. */
export const t = derived(settings, ($s) => {
  const dict: Record<string, string> = dictionaries[$s.language] ?? dictionaries.en;
  return (key: TranslationKey, vars?: Record<string, string | number>): string => {
    let out = dict[key] ?? (en as Record<string, string>)[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
    return out;
  };
});

